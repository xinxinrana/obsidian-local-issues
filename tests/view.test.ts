import test from 'node:test';
import assert from 'node:assert/strict';
import { build } from 'esbuild';
import { createRequire } from 'node:module';
import vm from 'node:vm';
import { JSDOM } from 'jsdom';
import { Store } from '../src/store';
import type { VaultAdapter } from '../src/types';
const require = createRequire(import.meta.url), mock = require('./obsidian-mock.cjs');
async function until(check: () => boolean | Promise<boolean>, label: string) {
  const deadline = Date.now() + 3000;
  while (Date.now() < deadline) { if (await check()) return; await new Promise(r => setTimeout(r, 5)); }
  assert.fail(`未完成：${label}。通知：${mock.notices.join(' / ')}`);
}
test('real view supports project → issue → Markdown comments, pasted and dropped attachments, boards and conflicts', async () => {
  const dom = new JSDOM('<!doctype html><body></body>', { url: 'http://localhost' });
  for (const name of ['document', 'window', 'HTMLElement', 'HTMLTextAreaElement', 'HTMLInputElement', 'HTMLLabelElement', 'HTMLSelectElement', 'Element', 'Node', 'Event', 'MouseEvent']) (globalThis as any)[name] = (dom.window as any)[name];
  mock.installDom(dom.window);
  mock.notices.length = 0; mock.menus.length = 0;
  const files = new Map<string, string>(), binary = new Map<string, Uint8Array>();
  const adapter: VaultAdapter = { list: async () => [...files.keys()], read: async p => files.get(p)!,
    write: async (p, text, expectedRaw) => { if (expectedRaw !== undefined && files.get(p) !== expectedRaw) throw new Error('写入冲突'); files.set(p, text); }, exists: async p => files.has(p) || binary.has(p),
    writeBinary: async (p, bytes) => { binary.set(p, bytes); } };
  const store = new Store(adapter), copied: string[] = [], opened: string[] = [], shared: string[] = [];
  const app = { vault: { getMarkdownFiles: () => [...files.keys()].map(path => ({ path })) }, workspace: { openLinkText: async () => {} } };
  const host = { store, author: 'Evan', openNote: async (path: string) => { opened.push(path); }, agentCommand: async (ref: string) => { shared.push(ref); return "node '/vault/cli.mjs' issue view 'http://127.0.0.1:27183/share-test' --json"; }, openSettings() {} };
  const built = await build({ entryPoints: ['src/view.ts'], bundle: true, write: false, format: 'cjs', platform: 'node', external: ['obsidian'], logLevel: 'silent' });
  const module = { exports: {} as any };
  vm.runInNewContext(built.outputFiles[0].text, { module, exports: module.exports, require: (id: string) => id === 'obsidian' ? mock : require(id),
    document: dom.window.document, window: dom.window, HTMLElement: dom.window.HTMLElement, HTMLInputElement: dom.window.HTMLInputElement,
    HTMLTextAreaElement: dom.window.HTMLTextAreaElement, HTMLLabelElement: dom.window.HTMLLabelElement, HTMLSelectElement: dom.window.HTMLSelectElement, Event: dom.window.Event, Node: dom.window.Node, Element: dom.window.Element,
    navigator: { clipboard: { writeText: async (s: string) => { copied.push(s); } } }, setTimeout, clearTimeout, Uint8Array, console,
  });
  const view = new module.exports.IssuesView({ app }, host);
  const click = (name: string, parent: HTMLElement = view.contentEl) => {
    const button = [...parent.querySelectorAll('button')].find(b => b.textContent === name) as HTMLButtonElement;
    assert.ok(button, `缺少按钮 ${name}`); button.click();
  };
  const assertFooter = (modal: any) => {
    const footer = modal.modalEl.querySelector(':scope > .li-modal-actions');
    assert.ok(footer, '保存栏直接属于 modalEl');
    assert.equal(modal.contentEl.parentElement, modal.modalEl);
    assert.equal(modal.contentEl.nextElementSibling, footer, '保存栏位于正文滚动区之后');
    assert.ok(!modal.contentEl.contains(footer), '保存栏与 contentEl 为兄弟节点');
    assert.deepEqual([...footer.querySelectorAll('button')].map((b: any) => b.textContent), ['取消', '保存']);
  };
  const menuAction = (name: string) => { const menu = mock.menus.at(-1); assert.ok(menu?.shown, '菜单应已显示'); menu.select(name); };
  const fill = (node: HTMLInputElement | HTMLTextAreaElement, value: string) => { assert.ok(node); node.value = value; node.dispatchEvent(new dom.window.Event('input', { bubbles: true })); };
  try {
    await view.onOpen(); assert.match(view.contentEl.textContent, /把想法变成项目/);
    click('创建第一个项目'); let modal = mock.modals.at(-1); assertFooter(modal);
    fill(modal.contentEl.querySelector('input[placeholder="项目名称"]'), '界面项目');
    fill(modal.contentEl.querySelector('textarea'), '项目正文 [[Reference]]'); click('保存', modal.modalEl);
    await until(async () => (await store.snapshot()).projects.length === 1 && !mock.modals.length && !!view.contentEl.querySelector('input[aria-label="搜索 Issues"]'), '创建项目');
    const project = (await store.snapshot()).projects[0];
    click('+ 新建 Issue'); modal = mock.modals.at(-1); assertFooter(modal);
    const properties = modal.contentEl.querySelector('details.li-properties');
    assert.ok(properties); assert.equal(properties.open, false, '新建 Issue 属性默认折叠');
    assert.match(properties.querySelector('summary').textContent, /属性与关联/);
    properties.querySelector('summary').click(); assert.equal(properties.open, true);
    fill(modal.contentEl.querySelector('input[placeholder="简洁描述这件事"]'), '从界面创建的议题');
    fill(modal.contentEl.querySelector('textarea'), '**描述** [[Reference]]');
    fill(modal.contentEl.querySelector('input[placeholder="多个标签用逗号分隔"]'), '功能,体验');
    click('保存', modal.modalEl);
    await until(async () => (await store.snapshot()).issues.length === 1 && !mock.modals.length && !!view.contentEl.querySelector('.li-composer'), '创建 Issue');
    const issue = (await store.snapshot()).issues[0];
    assert.equal(issue.author, 'Evan'); assert.deepEqual(issue.labels, ['功能', '体验']);
    const composer = () => view.contentEl.querySelector('.li-composer') as HTMLElement;
    let text = composer().querySelector('textarea') as HTMLTextAreaElement;
    fill(text, '第一条评论');
    const paste = new dom.window.Event('paste', { bubbles: true, cancelable: true });
    let finishPaste!: (bytes: ArrayBuffer) => void; const pasteBytes = new Promise<ArrayBuffer>(resolve => { finishPaste = resolve; });
    Object.defineProperty(paste, 'clipboardData', { value: { files: [{ name: 'clipboard.png', arrayBuffer: () => pasteBytes }] } });
    text.focus(); text.dispatchEvent(paste);
    assert.equal(text.dataset.uploading, 'true');
    click('发表评论', composer());
    await until(() => mock.notices.some((n: string) => n.includes('稍后发表评论')), '上传中禁止发表评论');
    assert.equal((await store.snapshot()).timeline.length, 0);
    await view.refresh(); assert.equal(composer().querySelector('textarea'), text); assert.equal(text.value, '第一条评论');
    finishPaste(Uint8Array.from([137, 80, 78, 71]).buffer);
    await until(() => text.value.includes('resource/local-issues/') && !text.dataset.uploading, '粘贴图片'); assert.ok(paste.defaultPrevented);
    click('发表评论', composer());
    await until(async () => (await store.snapshot()).timeline.length === 1 && view.contentEl.querySelector('.li-timeline .li-comment'), '发表评论');
    text = composer().querySelector('textarea')!; fill(text, '第二条评论');
    const drop = new dom.window.Event('drop', { bubbles: true, cancelable: true });
    Object.defineProperty(drop, 'dataTransfer', { value: { files: [{ name: 'notes.pdf', arrayBuffer: async () => Uint8Array.from([37, 80, 68, 70]).buffer }] } });
    text.closest('.li-editor')!.dispatchEvent(drop);
    await until(() => text.value.includes('notes.pdf'), '拖入附件'); click('发表评论', composer());
    await until(async () => (await store.snapshot()).timeline.length === 2 && view.contentEl.querySelectorAll('.li-timeline .li-comment').length === 2, '第二条评论');
    assert.equal(binary.size, 2);
    click('编辑', view.contentEl.querySelector('.li-timeline .li-comment')!); modal = mock.modals.at(-1); assertFooter(modal);
    const editText = modal.contentEl.querySelector('textarea'); fill(editText, '修改过的评论');
    let finishEditUpload!: (bytes: ArrayBuffer) => void; const editBytes = new Promise<ArrayBuffer>(resolve => { finishEditUpload = resolve; });
    const editPaste = new dom.window.Event('paste', { bubbles: true, cancelable: true });
    Object.defineProperty(editPaste, 'clipboardData', { value: { files: [{ name: 'edited.png', arrayBuffer: () => editBytes }] } });
    editText.dispatchEvent(editPaste); click('保存', modal.modalEl);
    await until(() => mock.notices.some((n: string) => n.includes('稍后保存')), '上传中禁止保存评论');
    assert.ok(mock.modals.includes(modal)); assert.equal(editText.value, '修改过的评论');
    finishEditUpload(Uint8Array.from([137, 80, 78, 71]).buffer);
    await until(() => editText.value.includes('edited.png') && !editText.dataset.uploading, '编辑评论上传完成');
    click('保存', modal.modalEl);
    await until(async () => (await store.snapshot()).timeline[0].body.includes('修改过的评论') && !mock.modals.length && view.contentEl.querySelector('.li-timeline .li-comment')?.textContent.includes('edited.png'), '编辑评论');
    assert.match((await store.snapshot()).timeline[0].body, /edited\.png/); assert.equal(binary.size, 3);
    click('关闭 Issue'); await until(async () => (await store.getIssue(issue.id)).status === 'closed' && view.contentEl.textContent.includes('重新打开 Issue'), '关闭 Issue');
    click('重新打开 Issue'); await until(async () => (await store.getIssue(issue.id)).status === 'open' && view.contentEl.textContent.includes('关闭 Issue'), '重新打开');
    assert.equal((await store.snapshot()).timeline.filter(t => t.kind === 'comment').length, 2);
    text = composer().querySelector('textarea')!; fill(text, '未发送的草稿'); text.focus(); await view.refresh();
    assert.equal((composer().querySelector('textarea') as HTMLTextAreaElement).value, '未发送的草稿');
    await view.navigate(project.id); click('看板');
    await until(() => !!view.contentEl.querySelector('.li-board'), '看板');
    assert.equal(view.contentEl.querySelectorAll('.li-board-column').length, 3);
    const status = view.contentEl.querySelector('.li-card select') as HTMLSelectElement; status.value = 'in-progress'; status.dispatchEvent(new dom.window.Event('change'));
    const oldBoard = view.contentEl.querySelector('.li-board');
    await until(async () => (await store.getIssue(issue.id)).status === 'in-progress' && view.contentEl.querySelector('.li-board') !== oldBoard, '看板状态');
    await view.navigate(project.id, issue.id); assert.equal((composer().querySelector('textarea') as HTMLTextAreaElement).value, '未发送的草稿');
    assert.ok(![...view.contentEl.querySelectorAll('.li-detail-actions button')].some((b: any) => b.textContent === '分享给 Agent'), '次要操作收纳于菜单');
    click('更多', view.contentEl.querySelector('.li-detail-actions')!); menuAction('分享给 Agent');
    await until(() => copied.length === 1, '菜单分享'); assert.deepEqual(shared, [issue.id]);
    assert.match(copied[0], /^node .* issue view .* --json$/); assert.equal(copied[0].split('\n').length, 1);
    click('更多', view.contentEl.querySelector('.li-detail-actions')!); menuAction('复制双链');
    await until(() => copied.length === 2, '菜单复制双链'); assert.ok(copied[1].includes(issue.path.replace(/\.md$/, '')));
    click('更多', view.contentEl.querySelector('.li-detail-actions')!); menuAction('打开笔记');
    await until(() => opened.length === 1, '菜单打开笔记'); assert.equal(opened[0], issue.path);
    click('编辑', view.contentEl.querySelector('.li-detail-actions')!); modal = mock.modals.at(-1); assertFooter(modal);
    assert.equal(modal.contentEl.querySelector('details.li-properties').open, false, '编辑 Issue 属性也默认折叠');
    fill(modal.contentEl.querySelector('textarea'), '旧界面修改');
    files.set(issue.path, files.get(issue.path)!.replace('**描述** [[Reference]]', '外部编辑正文'));
    click('保存', modal.modalEl); await until(() => mock.notices.some((n: string) => n.includes('冲突')), '冲突提示');
    assert.equal((await store.getIssue(issue.id)).body, '外部编辑正文');
    assert.ok(mock.modals.length); assert.equal(modal.contentEl.querySelector('textarea').value, '旧界面修改');
    modal.close();
    await view.navigate(project.id);
    click('表格'); await until(() => !!view.contentEl.querySelector('.li-issues-table'), '表格视图');
    assert.match(view.contentEl.querySelector('.li-issues-table').textContent, /从界面创建的议题/);
    click('字段'); menuAction('负责人');
    await until(() => view.contentEl.querySelectorAll('.li-issues-table th')[5].hidden, '隐藏字段');
    const search = view.contentEl.querySelector('input[aria-label="搜索 Issues"]');
    assert.ok(search.closest('.li-search-row')); assert.ok(!search.closest('.li-toolbar'));
    const filters = view.contentEl.querySelector('details.li-advanced-filters'); assert.ok(filters); assert.equal(filters.open, false);
    assert.equal(filters.querySelectorAll('select').length, 2);
    const oldSearchTable = view.contentEl.querySelector('.li-issues-table');
    search.value = '修改过的评论'; search.dispatchEvent(new dom.window.KeyboardEvent('keydown', { key: 'Enter', bubbles: true }));
    await until(() => !!view.contentEl.querySelector('.li-issues-table') && view.contentEl.querySelector('.li-issues-table') !== oldSearchTable, '评论全文搜索');
    assert.match(view.contentEl.querySelector('.li-issues-table').textContent, /从界面创建的议题/);
    await view.navigate(project.id, issue.id);
    click('+ 添加子议题'); modal = mock.modals.at(-1); assertFooter(modal);
    assert.equal(modal.contentEl.querySelector('details.li-properties').open, false);
    assert.match(modal.contentEl.querySelector('.li-property-summary').textContent, /父议题/);
    fill(modal.contentEl.querySelector('input[placeholder="简洁描述这件事"]'), '子议题'); click('保存', modal.modalEl);
    await until(async () => (await store.snapshot()).issues.length === 2 && !mock.modals.length, '新建子议题');
    const child = (await store.snapshot()).issues.find(i => i.title === '子议题')!; assert.equal(child.parent, issue.id);
    await view.navigate(project.id, issue.id); assert.match(view.contentEl.querySelector('.li-relations').textContent, /子议题/);
    await view.navigate();
    assert.equal(view.contentEl.querySelector('progress').value, 0);
    const projectSearch = view.contentEl.querySelector('input[aria-label="搜索项目"]'); projectSearch.value = '没有的项目';
    projectSearch.dispatchEvent(new dom.window.KeyboardEvent('keydown', { key: 'Enter', bubbles: true }));
    await until(() => view.contentEl.textContent.includes('没有匹配的项目'), '项目搜索');
  } finally { for (const modal of [...mock.modals]) modal.close(); await view.onClose(); dom.window.close(); }
});
